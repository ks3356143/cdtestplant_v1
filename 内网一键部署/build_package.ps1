# 内网一键部署打包脚本 —— 只在开发机上运行
# 用法：powershell -NoProfile -ExecutionPolicy Bypass -File .\build_package.ps1
# 产物：<项目根>\cdtestplant-offline\（纯英文路径，拷到内网 Windows 机器双击 一键启动.bat 即用）
#
# 依赖本机三样东西：便携 CPython（uv 管的 3.13）、项目 .venv 的依赖、node/npm（前端构建）。
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot      # 项目根
# 产物必须放在纯英文路径：MySQL 8.4 便携版无法在含中文的路径下运行
$pkg  = Join-Path $root 'cdtestplant-offline'

$pyRuntime = 'D:\programs\uv\python\cpython-3.13.11-windows-x86_64-none'
$venvSite  = Join-Path $root '.venv\Lib\site-packages'

foreach ($p in @($pyRuntime, $venvSite)) {
    if (-not (Test-Path $p)) { throw "缺少必要目录：$p" }
}

# robocopy 退出码 0-7 都算成功（1=有文件被复制），≥8 才是失败
function Copy-Tree($src, $dst) {
    robocopy $src $dst /E /XD __pycache__ /NFL /NDL /NJH /NJS /NP | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "robocopy 失败：$src (code $LASTEXITCODE)" }
    $global:LASTEXITCODE = 0
}

Write-Host "== 0/7 清理旧产物 =="
if (Test-Path $pkg) { Remove-Item $pkg -Recurse -Force }

Write-Host "== 1/7 Python 运行时 + 全部依赖 =="
Copy-Tree $pyRuntime (Join-Path $pkg 'python')
Copy-Tree $venvSite  (Join-Path $pkg 'python\Lib\site-packages')

Write-Host "== 2/7 便携 MySQL（含 data 现成数据）/ Redis / nginx =="
Copy-Tree (Join-Path $root 'packagesInitialize\mysql-8.4.3-winx64') (Join-Path $pkg 'mysql-8.4.3-winx64')
# MySQL 8.4 zip 版不带 VC++ 运行库，新机器没装 VC++ 2015-2022 x64 会起不来，直接补进 bin 做全自包含
$vcdlls = 'vcruntime140.dll', 'vcruntime140_1.dll', 'msvcp140.dll'
foreach ($d in $vcdlls) {
    $dst = Join-Path $pkg 'mysql-8.4.3-winx64\bin' $d
    if (-not (Test-Path $dst)) { Copy-Item "C:\Windows\System32\$d" $dst }
}
Copy-Tree (Join-Path $root 'packagesInitialize\redis')               (Join-Path $pkg 'redis')
Copy-Tree (Join-Path $root 'packagesInitialize\nginx-1.28.0')       (Join-Path $pkg 'nginx-1.28.0')
# 旧包里的前端产物、nginx 旧日志清掉，换新构建
Remove-Item (Join-Path $pkg 'nginx-1.28.0\html\dist') -Recurse -Force -ErrorAction SilentlyContinue
Remove-Item (Join-Path $pkg 'nginx-1.28.0\logs\*') -Force -ErrorAction SilentlyContinue
Copy-Item (Join-Path $PSScriptRoot 'nginx.conf') (Join-Path $pkg 'nginx-1.28.0\conf\nginx.conf') -Force

Write-Host "== 3/7 前端构建（intranet 模式，同源相对路径）=="
Push-Location (Join-Path $root 'web\cdTMP')
npm run build:intranet
if ($LASTEXITCODE -ne 0) { Pop-Location; throw '前端构建失败' }
Pop-Location
Copy-Tree (Join-Path $root 'web\cdTMP\dist') (Join-Path $pkg 'nginx-1.28.0\html\dist')

Write-Host "== 4/7 后端源码 =="
$app = Join-Path $pkg 'app'
Copy-Tree (Join-Path $root 'apps')           (Join-Path $app 'apps')
Copy-Tree (Join-Path $root 'conf')           (Join-Path $app 'conf')
Copy-Tree (Join-Path $root 'cdtestplant_v1') (Join-Path $app 'cdtestplant_v1')
Copy-Tree (Join-Path $root 'utils')          (Join-Path $app 'utils')
Copy-Tree (Join-Path $root 'templates')       (Join-Path $app 'templates')
Copy-Item (Join-Path $root 'manage.py') $app
Copy-Item (Join-Path $root 'run.py')    $app
# media 只带文档模板等输入资产，排除程序生成的输出目录
robocopy (Join-Path $root 'media') (Join-Path $app 'media') /E /XD __pycache__ output_dir final_seitai temp reuse temporary backup /NFL /NDL /NJH /NJS /NP | Out-Null
if ($LASTEXITCODE -ge 8) { throw 'media 拷贝失败' }
$global:LASTEXITCODE = 0
# 生成代码会直接往这些目录写文件且不自建目录（如 sm.py 的 form_template/sm/temporary），
# 源 media 里存在的一律以空目录形式镜像进包，否则全新环境首次文档生成会 FileNotFoundError
$excluded = 'output_dir','final_seitai','temp','reuse','temporary','backup'
$mediaSrc = Join-Path $root 'media'
Get-ChildItem $mediaSrc -Recurse -Directory | Where-Object { $excluded -contains $_.Name } | ForEach-Object {
    $rel = $_.FullName.Substring($mediaSrc.Length + 1)
    New-Item -ItemType Directory -Force (Join-Path $app ('media\' + $rel)) | Out-Null
}
# 存量项目再铺一遍 conf/base_document 的目录骨架（与新建项目 copytree 的结果对齐），
# 保证 output_dir/sm 等输出子目录在全新环境就位
$baseDoc = Join-Path $root 'conf\base_document'
Get-ChildItem (Join-Path $app 'media') -Directory | Where-Object { Test-Path (Join-Path $_.FullName 'form_template') } | ForEach-Object {
    $projDir = $_.FullName
    Get-ChildItem $baseDoc -Recurse -Directory | ForEach-Object {
        New-Item -ItemType Directory -Force (Join-Path $projDir ($_.FullName.Substring($baseDoc.Length + 1))) | Out-Null
    }
}
New-Item -ItemType Directory -Force (Join-Path $app 'logs'), (Join-Path $app 'uploads'), (Join-Path $app 'static') | Out-Null

Write-Host "== 5/7 生成 app\.env + collectstatic =="
# FIELD_ENCRYPTION_KEY 沿用本机 .env（保证库里的历史密文可解）；DJANGO_SECRET_KEY 每次打包随机生成
$devEnv = @{}
Get-Content (Join-Path $root '.env') | ForEach-Object {
    if ($_ -match '^\s*([A-Z_]+)\s*=\s*(.*?)\s*$') { $devEnv[$Matches[1]] = $Matches[2] }
}
if (-not $devEnv['FIELD_ENCRYPTION_KEY']) { throw '本机 .env 缺少 FIELD_ENCRYPTION_KEY' }
$chars = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!@#$%^&*(-_=+)'
$rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
$bytes = New-Object byte[] 50
$rng.GetBytes($bytes)
$secretKey = -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
$envText = @"
# Auto-generated by build_package.ps1 (neiwu one-click deploy). Edit + restart to apply.
DJANGO_SECRET_KEY=$secretKey
FIELD_ENCRYPTION_KEY=$($devEnv['FIELD_ENCRYPTION_KEY'])
ALLOWED_HOSTS=*
DATABASE_HOST=127.0.0.1
DATABASE_PORT=3307
DATABASE_USER=root
DATABASE_PASSWORD=root
DATABASE_NAME=chengdu_test_plant_v1
# Set to true when the intranet can reach the company AD (dns.paisat.cn:389).
ENABLE_LDAP_AUTH=false
"@
Set-Content -Path (Join-Path $app '.env') -Value $envText -Encoding Ascii

$pyExe = Join-Path $pkg 'python\python.exe'
$env:DJANGO_SETTINGS_MODULE = 'cdtestplant_v1.settings'
Push-Location $app
& $pyExe manage.py collectstatic --noinput
if ($LASTEXITCODE -ne 0) { Pop-Location; throw 'collectstatic 失败' }
Pop-Location
Remove-Item Env:DJANGO_SETTINGS_MODULE -ErrorAction SilentlyContinue

Write-Host "== 6/7 拷入启动脚本/说明/dbdata.sql + 依赖自检 =="
Copy-Item (Join-Path $PSScriptRoot '一键启动.bat') $pkg -Force
Copy-Item (Join-Path $PSScriptRoot '一键停止.bat') $pkg -Force
Copy-Item (Join-Path $PSScriptRoot '部署说明.md')  $pkg -Force
Copy-Item (Join-Path $root 'packagesInitialize\dbdata.sql') $pkg -Force
& $pyExe -c "import django, ldap, orjson, waitress, docxtpl, lxml, PIL; print('依赖导入 OK')"

Write-Host "== 7/7 完成 =="
$sum = (Get-ChildItem $pkg -Recurse -Force -ErrorAction SilentlyContinue | Measure-Object Length -Sum).Sum
Write-Host ("产物：{0}  大小：{1:N1} GB" -f $pkg, ($sum / 1GB))
Write-Host '拷到内网机器后双击 一键启动.bat 即可。'
